import assert from 'node:assert/strict'
export async function workspaceFlow({js,click,waitText,setInput,open,login,logout,loadPage,until,send,writeFile,resolve,artifactRoot,A,B,calls,rows,members}) {
 const key=id=>`stage-strike.workspace.v1:abcdefghijklmnopqrst:${A}:${id}`
 const data=id=>js(`JSON.parse(localStorage.getItem(${JSON.stringify(key(id))}))`)
 await js(`localStorage.setItem('stage-strike.top8.v1',JSON.stringify({schemaVersion:1,status:'draft',participants:Array.from({length:8},(_,i)=>({id:'old'+i,nickname:'OLD '+i,characterIds:[]})),seeds:[],results:{}}))`)
 const legacy=await js("localStorage.getItem('stage-strike.top8.v1')")
 await login('a@example.invalid')
 const ids=[]
 for(const [name,count]of[['Noviembre',16],['Diciembre',32]]){
  await setInput('[name=remote-tournament-name]',name);await click('Crear torneo');await waitText('Torneo creado')
  const id=rows.find(t=>t.name===name).id;ids.push(id)
  assert.equal((await data(id)).tournament,null)
  assert.equal((await data(id)).registration.participants.length,0)
  await js(`(()=>{const card=[...document.querySelectorAll('li')].find(li=>li.querySelector('h3')?.textContent===${JSON.stringify(name)});[...card.querySelectorAll('button')].find(b=>b.textContent==='Abrir torneo').click()})()`)
  await waitText('Torneo actual: '+name);await waitText('Agregar participante')
  assert.equal(await js("document.querySelectorAll('.registration-list li').length"),0)
  await js("[...document.querySelectorAll('summary')].find(x=>x.textContent==='Pegar lista').click()")
  await setInput('textarea',Array.from({length:count},(_,i)=>`${name} ${i}`).join('\n'))
  await click('Revisar lista');await click('Confirmar importación');await waitText('Lista guardada.')
  assert.equal((await data(id)).registration.participants.length,count)
  await click('Bracket');await waitText('Elegir participantes del registro');await click('Seleccionar todos');await click('Revisar selección');await click('Confirmar nuevo torneo')
  await waitText('Distribución');await click('Generar bracket');await click('Iniciar torneo')
  await until(async()=>JSON.parse((await data(id)).tournament).status==='started','started '+name)
  await open('/tournament/match/W1?event='+id);await waitText('DQ / Descalificar')
  // Exercise actual VS write path, not a storage fixture.
  await click('DQ / Descalificar');await setInput('.dq-controls select','1');await setInput('.dq-controls input','Fixture '+name);await click('Confirmar DQ…');await waitText('Revertir DQ')
  assert.equal(JSON.parse((await data(id)).tournament).results.W1.outcome.type,'dq')
  await click('Mis torneos');await waitText('Crear torneo')
 }
 const [nov,dec]=ids, novSaved=await data(nov), decSaved=await data(dec)
 await open('/registration?event='+nov);await waitText('Agregar participante')
 assert.equal(await js("document.querySelectorAll('.registration-list li').length"),16)
 await setInput('[aria-label="Cambiar torneo"]',dec);await waitText('Torneo actual: Diciembre');await waitText('Agregar participante')
 assert.equal((await data(nov)).tournament,novSaved.tournament)
 await setInput('[aria-label="Cambiar torneo"]',nov);await waitText('Torneo actual: Noviembre');await waitText('Agregar participante')
 await loadPage('Page.reload');await waitText('Agregar participante')
 assert.equal(await js("document.querySelectorAll('.registration-list li').length"),16)
 assert.deepEqual(await data(dec),decSaved)
 await click('Bracket');await waitText('BRACKET');await until(()=>js("document.body.innerText.includes('DQ')"),'DQ survived navigation')
 await open('/tournament/standings?event='+nov);await waitText('Resultados provisionales')
 assert.deepEqual(await data(nov),novSaved)
 // Explicit legacy migration preview/cancel: never automatic assignment.
 await open('/registration?event='+nov);await waitText('Agregar participante')
 await js("[...document.querySelectorAll('summary')].find(x=>x.textContent==='Recuperar datos locales anteriores').click()")
 await click('Vista previa de datos antiguos');await waitText('OLD 0')
 assert.deepEqual(await data(nov),novSaved)
 assert.equal(await js("localStorage.getItem('stage-strike.top8.v1')"),legacy)
 await click('Mis torneos');await waitText('Crear torneo')
 await js("[...document.querySelectorAll('li')].find(li=>li.querySelector('h3')?.textContent==='Noviembre').querySelectorAll('button')[1].click()")
 await click('Vista previa del torneo local');await waitText('16 participantes');await waitText('todavía no se puede subir')
 assert.equal(calls.filter(c=>c.name==='ss_initialize_tournament_draft').length,0)
 // Backend membership fixtures represent accepted invitation; identity comes from Auth.
 members.push({tournament_id:nov,profile_id:B,role:'admin'})
 await logout();await login('b@example.invalid');await open('/registration?event='+nov);await waitText('Agregar participante')
 assert.equal(await js("document.querySelectorAll('.registration-list li').length"),0,'other account never inherits local data')
 await open('/registration?event='+dec);await waitText('Tu cuenta no administra este torneo')
 assert.equal(await js("!!document.querySelector('.registration-page')"),false)
 await logout();await login('a@example.invalid');await open('/registration?event='+nov);await waitText('Agregar participante')
 assert.deepEqual(await data(nov),novSaved);assert.deepEqual(await data(dec),decSaved)
 assert.equal(await js(`navigator.locks.request(${JSON.stringify(key(nov))},{ifAvailable:true},lock=>lock===null)`),true,'active editor owns exclusive lock')
 await click('Mis torneos');await waitText('Crear torneo')
 await setInput('[name=remote-tournament-name]','Recuperacion');await click('Crear torneo');await waitText('Torneo creado')
 const recovery=rows.find(t=>t.name==='Recuperacion').id
 await open('/registration?event='+recovery);await waitText('Agregar participante')
 await js("[...document.querySelectorAll('summary')].find(x=>x.textContent==='Recuperar datos locales anteriores').click()")
 await click('Vista previa de datos antiguos');await waitText('OLD 0');await click('Confirmar recuperación');await waitText('Copia local recuperada')
 assert.equal((await data(recovery)).tournament,legacy)
 assert.equal(await js("localStorage.getItem('stage-strike.top8.v1')"),legacy)
 await open('/tournament?event='+recovery);await waitText('BRACKET')
 const fixturePath=resolve(artifactRoot,'tournament-import.json');await writeFile(fixturePath,novSaved.tournament)
 const document=await send('DOM.getDocument'), field=await send('DOM.querySelector',{nodeId:document.root.nodeId,selector:'input[aria-label="Archivo JSON del torneo"]'})
 await send('DOM.setFileInputFiles',{nodeId:field.nodeId,files:[fixturePath]});await waitText('Torneo importado correctamente')
 assert.deepEqual(JSON.parse((await data(recovery)).tournament),JSON.parse(novSaved.tournament))
 assert.deepEqual(await data(nov),novSaved);assert.deepEqual(await data(dec),decSaved)
 await open('/registration?event='+nov);await waitText('Agregar participante')
 await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true})
 assert.ok(await js('document.documentElement.scrollWidth<=innerWidth'))
 const shot=await send('Page.captureScreenshot',{format:'png',captureBeyondViewport:true});await writeFile(resolve(artifactRoot,'workspace-mobile.png'),Buffer.from(shot.data,'base64'))
 console.log('PASS: 16/32 independent rosters, blank creation, real bracket/DQ UI, switch/reload, standings, legacy preview/no overwrite, scoped cloud preview, account/admin isolation and foreign denial; no remote network.')
}
